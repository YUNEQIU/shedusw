// 首页搜索框的处理
function searchSoftware() {
  const query = document.getElementById("searchInput")?.value.trim();
  if (query) {
    window.location.href = `results.html?query=${encodeURIComponent(query)}`;
  }
}

// 搜索结果页面的处理
function handleSearchResults() {
  const query = new URLSearchParams(window.location.search).get("query");
  if (query) {
    const filteredSoftware = softwareData.filter((software) =>
      software.name.toLowerCase().includes(query.toLowerCase())
    );
    displaySoftwareList(filteredSoftware);
  }
}

function displaySoftwareList(softwareList) {
  const listElement = document.getElementById("softwareList");
  if (!listElement) return; // 防止非搜索结果页出错

  listElement.innerHTML = "";

  if (softwareList.length === 0) {
    listElement.innerHTML = "<li>😔 很遗憾，没有检索到相应关键字的资源，请更换关键字再次检索，也可以尝试联系我们的设计团队成员。</li>";
  } else {
    softwareList.forEach((software) => {
      const listItem = document.createElement("li");

      const thumbnail = document.createElement("img");
      thumbnail.src = software.thumbnail;
      thumbnail.alt = software.name + "缩略图";
      thumbnail.classList.add("software-thumbnail");

      const nameText = document.createElement("span");
      nameText.textContent = software.name;

      listItem.appendChild(thumbnail);
      listItem.appendChild(nameText);

      listItem.onclick = () => {
        window.location.href = software.page;
      };

      listElement.appendChild(listItem);
    });
  }
}

// 通用的加载模块函数
function loadModule(file, targetId, callback) {
  fetch(file)
    .then(response => response.text())
    .then(data => {
      document.getElementById(targetId).innerHTML = data;
      if (callback) callback();  // 加载后回调
    })
    .catch(err => console.error(`加载 ${file} 失败：`, err));
}

// 加载 header，并在加载完后绑定 header 内的事件
loadModule('header.html', 'header', () => {
  const searchInput = document.getElementById("searchInput");
  if (searchInput) {
    searchInput.addEventListener("keydown", function (event) {
      if (event.key === "Enter") {
        searchSoftware();
      }
    });

    const searchButton = document.querySelector('.search button');
    if (searchButton) {
      searchButton.addEventListener('click', searchSoftware);
    }
  }
});

// 加载 footer
loadModule('footer.html', 'footer');

// 监听页面加载，处理搜索结果
window.addEventListener('load', handleSearchResults);

//易拉宝
const photos = document.querySelectorAll(".photo");

function applyCoverFlow(centerIndex) {
  const baseDistance = 0; // 基准水平偏移像素
  const compression = 0.5; // 越往外越靠拢

  photos.forEach((p, i) => {
    const offset = i - centerIndex;

    if (offset === 0) {
      // 中心图
      p.style.transform = `translateX(0px) scale(1.4) rotateY(0deg)`;
      p.style.zIndex = 10;
      p.style.filter = "brightness(1)";
    } else {
      // 左右图
      const direction = offset > 0 ? -1 : 1;
      const absOffset = Math.abs(offset);
      const angle = Math.min(absOffset * 25, 75);
      const translate = offset * baseDistance * Math.pow(compression, absOffset);

      p.style.transform = `translateX(${translate}px) scale(0.9) rotateY(${angle * direction}deg)`;
      p.style.zIndex = 10 - absOffset;
      p.style.filter = "brightness(0.6)";
    }
  });
}

photos.forEach((photo, index) => {
  photo.addEventListener("mouseenter", () => applyCoverFlow(index));
  photo.addEventListener("mouseleave", () => applyCoverFlow(defaultIndex));
});

const defaultIndex = Math.floor(photos.length / 2);
applyCoverFlow(defaultIndex);
